function daysAgo(days, hour) {
  const date = new Date();
  date.setDate(date.getDate() - days);
  date.setHours(hour, 12, 0, 0);
  return date.toISOString();
}

function line(productId, name, image, quantity, base, custom, options) {
  const unit = Math.round((base + custom) * 100) / 100;
  return {
    id: crypto.randomUUID(),
    productId,
    productName: name,
    image,
    quantity,
    basePrice: base,
    customizationPrice: custom,
    totalPrice: Math.round(unit * quantity * 100) / 100,
    options,
  };
}

